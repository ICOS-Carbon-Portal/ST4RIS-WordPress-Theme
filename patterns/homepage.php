<!-- INTRO -->
<section class="intro" id="why">
  <div class="inner">
    <h2>Why ST4RIS</h2>
    <p>European Research Infrastructures rely on highly skilled technical staff. Despite this central role, RI technical staff face fragmented training opportunities, unclear career pathways, limited mobility, and insufficient recognition in institutional human resource strategies.</p>
    <p>ST4RIS addresses these challenges by developing a co-designed, interoperable training and career development framework for RI professionals, contributing to a more coherent and sustainable European research infrastructure landscape.</p>
  </div>
</section>

